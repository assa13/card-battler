// Иконки карт умений.
//
// Лист из 17 рисунков нарезан на отдельные файлы `public/assets/cards/icons/`,
// имя файла — id умения. Так сопоставление не может разъехаться: раньше здесь
// была таблица «умение → номер на листе», и номера были расставлены неверно.
//
// Раскладка листа взята из icon-atlas/card-icons/manifest.json ветки
// test/dungeon-sector-map, где эти иконки и рисовались: пять умений на героя
// подряд (базовое и четыре навыка), потом следующий герой, в конце две
// карты-модификатора. Четыре навыка — не опечатка: два из них заморожены и в
// HERO_ABILITIES пока не заведены, но рисунки на них уже есть и лежат здесь же.
//
// Рисунки не пиксель-арт, а сглаженная живопись (118 тысяч цветов в исходнике),
// поэтому они лежат в обычном WebP с потерями и рисуются без pixelated: на них
// это дало бы рваную кромку.

const CARD_ICON_IDS = new Set([
  'b1', 's1_1', 's1_2', 's1_3', 's1_4',
  'b2', 's2_1', 's2_2', 's2_3', 's2_4',
  'b3', 's3_1', 's3_2', 's3_3', 's3_4',
  'mod_armor', 'mod_chain',
]);

/**
 * Ключ ищется не по id карты: в колоде лежит экземпляр (start_p1,
 * persist_p1_s1_1, mod_start_armor), а исходное умение он помнит в skillId.
 * Мод-карты skillId не имеют, зато их опознаёт modType.
 */
export const getCardIconUrl = (card) => {
  if (!card) return null;
  const key = card.skillId || (card.modType ? `mod_${card.modType}` : card.id);
  return CARD_ICON_IDS.has(key) ? `./assets/cards/icons/${key}.webp` : null;
};

export default CARD_ICON_IDS;
